-- Summary:
-- 1. Creates public.notifications table for in-app alerts (volunteers and admins).
-- 2. Strictly enforces RLS:
--    - Volunteers and Admins can read only their own notifications.
--    - Users can update only their own notifications (e.g. mark as read).
--    - Direct client-side INSERT is blocked to prevent notification spoofing.
-- 3. Employs a partial unique index on (user_id, deduplication_key) to guarantee
--    idempotency and eliminate duplicate notifications on retried operations.
-- 4. Creates public.create_admin_notifications_for_referral(...) with SECURITY DEFINER
--    to safely fan out notifications to all active profiles with role = 'admin'.
-- ==============================================================================

-- 1. Create Notifications Table
CREATE TABLE IF NOT EXISTS public.notifications (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('new_referral', 'referral_approved', 'referral_rejected', 'system')),
    link_url TEXT DEFAULT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    deduplication_key TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Indexes for Performance & Idempotency
-- Strict deduplication: prevents duplicate notifications for the same event key per recipient
CREATE UNIQUE INDEX IF NOT EXISTS idx_unique_notification_dedup
    ON public.notifications (user_id, deduplication_key);

-- Fast lookup for unread counts and recent notification drawers
CREATE INDEX IF NOT EXISTS idx_notifications_user_lookup
    ON public.notifications (user_id, is_read, created_at DESC);

-- 3. Row Level Security (RLS)
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

-- Select Policy: Users read strictly their own notifications
DROP POLICY IF EXISTS "Users can read own notifications" ON public.notifications;
CREATE POLICY "Users can read own notifications"
    ON public.notifications FOR SELECT
    USING (auth.uid() = user_id);

-- Update Policy: Users can only mutate their own read status
DROP POLICY IF EXISTS "Users can update own notification read status" ON public.notifications;
CREATE POLICY "Users can update own notification read status"
    ON public.notifications FOR UPDATE
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

-- Insert Policy: Explicitly forbid arbitrary direct client insertions
-- Notifications must be generated by authorized server-side RPCs or triggers
DROP POLICY IF EXISTS "Disallow direct client insertion" ON public.notifications;
CREATE POLICY "Disallow direct client insertion"
    ON public.notifications FOR INSERT
    WITH CHECK (FALSE);

-- 4. Database Function: Fan Out In-App Notifications to All Active Administrators
-- Triggered when a new referral is submitted.
CREATE OR REPLACE FUNCTION public.create_admin_notifications_for_referral(
    p_referral_id UUID
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_calling_user_id UUID;
    v_referral RECORD;
    v_volunteer RECORD;
    v_admin RECORD;
    v_admin_count INTEGER := 0;
    v_dedup_key TEXT;
    v_title TEXT;
    v_message TEXT;
    v_link TEXT;
    v_metadata JSONB;
BEGIN
    v_calling_user_id := auth.uid();
    IF v_calling_user_id IS NULL THEN
        RAISE EXCEPTION 'AUTHENTICATION_REQUIRED: Caller must be signed in.';
    END IF;

    -- Fetch the referral
    SELECT id, volunteer_id, buyer_name, ticket_type, ticket_quantity, order_reference, created_at
    INTO v_referral
    FROM public.referrals
    WHERE id = p_referral_id;

    IF v_referral.id IS NULL THEN
        RETURN pg_catalog.jsonb_build_object(
            'success', FALSE,
            'message', 'Referral not found.'
        );
    END IF;

    -- Verify that the caller is either the volunteer who owns the referral or an admin
    IF v_referral.volunteer_id <> v_calling_user_id AND NOT EXISTS (
        SELECT 1 FROM public.profiles WHERE id = v_calling_user_id AND role = 'admin'
    ) THEN
        RAISE EXCEPTION 'FORBIDDEN: Caller is not authorized to dispatch notifications for this referral.';
    END IF;

    -- Fetch volunteer profile details
    SELECT full_name, volunteer_team
    INTO v_volunteer
    FROM public.profiles
    WHERE id = v_referral.volunteer_id;

    -- Stable event deduplication key for this referral submission
    v_dedup_key := 'referral_submission_' || v_referral.id::TEXT;
    v_title := 'New Ticket Referral Submitted';
    v_message := COALESCE(v_volunteer.full_name, 'A volunteer') || ' (' ||
                 COALESCE(v_volunteer.volunteer_team, 'Volunteer Team') || ') submitted a claim for ' ||
                 v_referral.ticket_quantity::TEXT || 'x ' || v_referral.ticket_type || '.';
    v_link := '/admin?tab=referrals&id=' || v_referral.id::TEXT;

    v_metadata := pg_catalog.jsonb_build_object(
        'referral_id', v_referral.id,
        'volunteer_id', v_referral.volunteer_id,
        'volunteer_name', v_volunteer.full_name,
        'volunteer_team', v_volunteer.volunteer_team,
        'ticket_type', v_referral.ticket_type,
        'ticket_quantity', v_referral.ticket_quantity,
        'order_reference', v_referral.order_reference,
        'submitted_at', v_referral.created_at
    );

    -- Insert in-app notification for EVERY profile with role = 'admin'
    FOR v_admin IN
        SELECT id FROM public.profiles WHERE role = 'admin'
    LOOP
        INSERT INTO public.notifications (
            user_id,
            title,
            message,
            type,
            link_url,
            metadata,
            deduplication_key,
            is_read
        ) VALUES (
            v_admin.id,
            v_title,
            v_message,
            'new_referral',
            v_link,
            v_metadata,
            v_dedup_key,
            FALSE
        )
        ON CONFLICT (user_id, deduplication_key) DO NOTHING;

        v_admin_count := v_admin_count + 1;
    END LOOP;

    RETURN pg_catalog.jsonb_build_object(
        'success', TRUE,
        'admins_notified', v_admin_count,
        'deduplication_key', v_dedup_key
    );
END;
$$;

-- Secure the function execution
REVOKE ALL ON FUNCTION public.create_admin_notifications_for_referral(UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.create_admin_notifications_for_referral(UUID) TO authenticated;
